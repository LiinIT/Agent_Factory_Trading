import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';

import { scrubCommitMessage, scrubText } from '../src/scrub.ts';
import { testEnvironment } from './helpers.ts';

const PBXPROJ = '\t\t\t\tCODE_SIGN_STYLE = Automatic;\n\t\t\t\tDEVELOPMENT_TEAM = ABCDE12345;\n\t\t\t\tENABLE_BITCODE = NO;\n';

test('scrubText bỏ DEVELOPMENT_TEAM trong project Xcode, giữ cấu hình khác', () => {
  assert.equal(scrubText('ios/Runner.xcodeproj/project.pbxproj', PBXPROJ), '\t\t\t\tCODE_SIGN_STYLE = Automatic;\n\t\t\t\tENABLE_BITCODE = NO;\n');
  assert.equal(scrubText('notes.txt', 'DEVELOPMENT_TEAM = ABCDE12345;\n'), 'DEVELOPMENT_TEAM = ABCDE12345;\n');
});

test('scrubText bỏ dòng ghi dấu AI ở comment và markdown', () => {
  const dart = 'void main() {}\n// Generated with Claude Code\n/// Co-Authored-By: Claude <noreply@anthropic.com>\nfinal a = 1;\n';
  assert.equal(scrubText('lib/main.dart', dart), 'void main() {}\nfinal a = 1;\n');
  assert.equal(scrubText('README.md', '# App\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n'), '# App\n\n');
  assert.equal(scrubText('a.py', 'x = 1  # generated by claude'), 'x = 1  # generated by claude');
});

test('scrubText không đụng code có nhắc tới Claude', () => {
  const code = "const label = 'Generated with Claude';\nprint('Co-Authored-By: Claude');\n";
  assert.equal(scrubText('lib/a.dart', code), code);
});

test('scrubCommitMessage bỏ trailer Co-Authored-By của AI', () => {
  assert.equal(scrubCommitMessage('feat: thêm màn hình\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n'), 'feat: thêm màn hình');
  assert.equal(scrubCommitMessage('fix: lỗi\n\nCo-Authored-By: Lan <lan@x.vn>'), 'fix: lỗi\n\nCo-Authored-By: Lan <lan@x.vn>');
});

test('commitAll lọc dấu ký và dấu AI trước khi commit', () => {
  const { workspace } = testEnvironment();
  workspace.create('demo', 'Demo', 'brief');
  const dir = workspace.projectDir('demo');
  writeFileSync(join(dir, 'project.pbxproj'), PBXPROJ);
  writeFileSync(join(dir, 'main.dart'), '// Generated with Claude Code\nvoid main() {}\n');
  assert.equal(workspace.commitAll('demo', 'feat: lát 1\n\nCo-Authored-By: Claude <noreply@anthropic.com>'), true);
  assert.equal(readFileSync(join(dir, 'main.dart'), 'utf8'), 'void main() {}\n');
  assert.doesNotMatch(readFileSync(join(dir, 'project.pbxproj'), 'utf8'), /DEVELOPMENT_TEAM/);
  const committed = execFileSync('git', ['show', 'HEAD:main.dart'], { cwd: dir, encoding: 'utf8' });
  assert.equal(committed, 'void main() {}\n');
  assert.equal(execFileSync('git', ['log', '-1', '--format=%B'], { cwd: dir, encoding: 'utf8' }).trim(), 'feat: lát 1');
});
